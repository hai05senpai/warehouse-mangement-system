-- =============================================================================
-- NẠP DỮ LIỆU DEMO LƯU TRỮ (mục 3.1) VÀO POSTGRESQL
--   psql "$DATABASE_PUBLIC_URL" < demo/storage/01_load_postgres.sql
-- Schema riêng storage_demo, không đụng dữ liệu của app (schema public).
--   inventory_one : bảng tồn kho chỉ có 1 dòng (đo chi phí cấp phát tối thiểu)
--   inventory     : 10.000 dòng tồn kho, cùng 6 cột và ràng buộc với bảng inventory của app
-- Chạy lại bất cứ lúc nào để đưa dữ liệu về trạng thái ban đầu.
-- =============================================================================
\set ON_ERROR_STOP on
SET client_min_messages = warning;

DROP SCHEMA IF EXISTS storage_demo CASCADE;
CREATE SCHEMA storage_demo;
SET search_path = storage_demo;

CREATE TABLE inventory_one (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id        bigint      NOT NULL,
    location_id       bigint      NOT NULL,
    quantity          integer     NOT NULL,
    reserved_quantity integer     NOT NULL,
    updated_at        timestamptz NOT NULL,
    UNIQUE (product_id, location_id)
);
INSERT INTO inventory_one (product_id, location_id, quantity, reserved_quantity, updated_at)
VALUES (1, 1, 100, 0, now());

CREATE TABLE inventory (LIKE inventory_one INCLUDING ALL);
-- 1.000 mặt hàng x 10 vị trí = 10.000 dòng tồn kho
INSERT INTO inventory (product_id, location_id, quantity, reserved_quantity, updated_at)
SELECT (g - 1) / 10 + 1, (g - 1) % 10 + 1, 100, 0, now()
FROM generate_series(1, 10000) g;

VACUUM ANALYZE inventory_one;
VACUUM ANALYZE inventory;

SELECT (SELECT count(*) FROM inventory) AS inventory_rows,
       pg_relation_size('inventory') / 8192 AS heap_pages;
