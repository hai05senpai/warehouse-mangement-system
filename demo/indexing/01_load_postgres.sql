-- Tạo schema riêng `idx_demo` (cùng cấu trúc bảng với app) với 100.000 dòng tồn kho.
-- KHÔNG tạo chỉ mục nào ngoài khóa chính / UNIQUE: việc tạo chỉ mục làm trong 03_demo_postgres.sql.
-- Chạy lại bất cứ lúc nào để đưa dữ liệu demo về trạng thái ban đầu.
