\set ON_ERROR_STOP on
SET client_min_messages = warning;

DROP SCHEMA IF EXISTS idx_demo CASCADE;
CREATE SCHEMA idx_demo;
CREATE EXTENSION IF NOT EXISTS pg_trgm WITH SCHEMA public;  -- cần cho chỉ mục GIN trigram ở bước demo
SET search_path = idx_demo, public;

CREATE TABLE products (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku          varchar(50)  NOT NULL UNIQUE,
    name         varchar(255) NOT NULL,
    category     varchar(50),
    unit         varchar(20),
    min_quantity integer
);
CREATE TABLE locations (
    id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code  varchar(50) NOT NULL UNIQUE,
    zone  varchar(50) NOT NULL,
    rack  varchar(50),
    shelf varchar(50)
);
CREATE TABLE inventory (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id        bigint  NOT NULL REFERENCES products (id),
    location_id       bigint  NOT NULL REFERENCES locations (id),
    quantity          integer NOT NULL,
    reserved_quantity integer NOT NULL,
    updated_at        timestamptz,
    UNIQUE (product_id, location_id)
);

SELECT setseed(0.42);  -- cố định dữ liệu ngẫu nhiên: mỗi lần nạp cho cùng kết quả

-- 2.000 vị trí, 20 khu không đều nhau:
--   Khu 01..10: khu chính, 190 vị trí/khu  (~9.500 dòng tồn = 9,5% bảng)
--   Khu 11..20: khu nhỏ,    10 vị trí/khu  (~500 dòng tồn   = 0,5% bảng)
INSERT INTO locations (code, zone, rack, shelf)
SELECT format('L%s', lpad(g::text, 4, '0')), format('Khu %s', lpad(z::text, 2, '0')),
       format('Kệ %s', g % 20 + 1), format('Tầng %s', g % 5 + 1)
FROM generate_series(1, 2000) g,
     LATERAL (SELECT CASE WHEN g <= 1900 THEN (g - 1) / 190 + 1 ELSE (g - 1901) / 10 + 11 END AS z) x;

-- 5.000 mặt hàng; 5% có ngưỡng cao => 250 mặt hàng tồn thấp
INSERT INTO products (sku, name, category, unit, min_quantity)
SELECT format('%s-%s', c, lpad(n::text, 5, '0')), format('Sản phẩm %s %s', c, n), c, 'Cái',
       CASE WHEN n % 20 = 0 THEN 1200 ELSE 300 END
FROM generate_series(1, 5000) n,
     LATERAL (SELECT (ARRAY['LAP','PHO','MON','ACC','TV','AC','REF','WAS','KB','CAM'])[n % 10 + 1] AS c) x;

-- 100.000 dòng tồn: mỗi mặt hàng ở 20 vị trí khác nhau (101 nguyên tố cùng nhau với 2000 => không trùng)
-- ~30% dòng bị giữ hết (không còn khả dụng)
INSERT INTO inventory (product_id, location_id, quantity, reserved_quantity, updated_at)
SELECT p, (p * 7 + k * 101) % 2000 + 1, q,
       CASE WHEN random() < 0.3 THEN q ELSE floor(random() * q)::int END, now()
FROM generate_series(1, 5000) p, generate_series(0, 19) k,
     LATERAL (SELECT floor(random() * 101 + 0 * k)::int AS q) x;

ANALYZE products; ANALYZE locations; ANALYZE inventory;

SELECT (SELECT count(*) FROM products)  AS products,
       (SELECT count(*) FROM locations) AS locations,
       (SELECT count(*) FROM inventory) AS inventory_rows;
