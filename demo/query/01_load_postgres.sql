\set ON_ERROR_STOP on
SET client_min_messages = warning;

DROP SCHEMA IF EXISTS qry_demo CASCADE;
CREATE SCHEMA qry_demo;
SET search_path = qry_demo;

CREATE TABLE products (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku          varchar(50)  NOT NULL UNIQUE,
    name         varchar(255) NOT NULL,
    min_quantity integer
);
CREATE TABLE inventory (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id        bigint  NOT NULL REFERENCES products (id),
    location_id       bigint  NOT NULL,
    quantity          integer NOT NULL,
    reserved_quantity integer NOT NULL DEFAULT 0,
    UNIQUE (product_id, location_id)
);
CREATE TABLE receipt_orders (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code         varchar(50) NOT NULL UNIQUE,
    status       varchar(20) NOT NULL,
    receipt_date timestamptz
);
CREATE TABLE receipt_items (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    receipt_order_id bigint  NOT NULL REFERENCES receipt_orders (id),
    product_id       bigint  NOT NULL REFERENCES products (id),
    location_id      bigint  NOT NULL,
    quantity         integer NOT NULL
);
CREATE TABLE issue_orders (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code       varchar(50) NOT NULL UNIQUE,
    status     varchar(20) NOT NULL,
    issue_date timestamptz
);
CREATE TABLE issue_items (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    issue_order_id bigint  NOT NULL REFERENCES issue_orders (id),
    product_id     bigint  NOT NULL REFERENCES products (id),
    location_id    bigint  NOT NULL,
    quantity       integer NOT NULL
);
CREATE TABLE stock_takes (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code            varchar(50) NOT NULL UNIQUE,
    status          varchar(20) NOT NULL,
    stock_take_date timestamptz
);
CREATE TABLE stock_take_items (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stock_take_id bigint  NOT NULL REFERENCES stock_takes (id),
    product_id    bigint  NOT NULL REFERENCES products (id),
    location_id   bigint  NOT NULL,
    system_qty    integer NOT NULL,
    actual_qty    integer NOT NULL
);

SELECT setseed(0.43);  -- cố định dữ liệu ngẫu nhiên

-- 5.000 mặt hàng, mỗi mặt hàng ở 4 vị trí => 20.000 dòng tồn
INSERT INTO products (sku, name, min_quantity)
SELECT format('%s-%s', c, lpad(n::text, 5, '0')), format('Sản phẩm %s %s', c, n), 100
FROM generate_series(1, 5000) n,
     LATERAL (SELECT (ARRAY['LAP','PHO','MON','ACC','TV','AC','REF','WAS','KB','CAM'])[n % 10 + 1] AS c) x;

INSERT INTO inventory (product_id, location_id, quantity)
SELECT p, (p * 7 + k * 53) % 200 + 1, floor(random() * 200 + 1)::int
FROM generate_series(1, 5000) p, generate_series(0, 3) k;

-- Một năm chứng từ (26/11/2025 .. 25/11/2026): 10.000 phiếu nhập, 10.000 phiếu xuất, 3 dòng / phiếu.
-- Trạng thái lệch: ~90% COMPLETED, ~7% PENDING, ~3% CANCELLED (dùng ở STEP 6).
INSERT INTO receipt_orders (code, status, receipt_date)
SELECT format('PN%s', lpad(g::text, 6, '0')), s.status,
       timestamptz '2025-11-26' + random() * interval '365 days'
FROM generate_series(1, 10000) g,
     LATERAL (SELECT CASE WHEN r < 0.90 THEN 'COMPLETED' WHEN r < 0.97 THEN 'PENDING' ELSE 'CANCELLED' END AS status
              FROM (SELECT random() + 0 * g AS r) t) s;

INSERT INTO issue_orders (code, status, issue_date)
SELECT format('PX%s', lpad(g::text, 6, '0')), s.status,
       timestamptz '2025-11-26' + random() * interval '365 days'
FROM generate_series(1, 10000) g,
     LATERAL (SELECT CASE WHEN r < 0.90 THEN 'COMPLETED' WHEN r < 0.97 THEN 'PENDING' ELSE 'CANCELLED' END AS status
              FROM (SELECT random() + 0 * g AS r) t) s;

INSERT INTO receipt_items (receipt_order_id, product_id, location_id, quantity)
SELECT o, floor(random() * 5000 + 1)::int + 0 * k, floor(random() * 200 + 1)::int, floor(random() * 50 + 1)::int
FROM generate_series(1, 10000) o, generate_series(1, 3) k;

INSERT INTO issue_items (issue_order_id, product_id, location_id, quantity)
SELECT o, floor(random() * 5000 + 1)::int + 0 * k, floor(random() * 200 + 1)::int, floor(random() * 30 + 1)::int
FROM generate_series(1, 10000) o, generate_series(1, 3) k;

-- Tạo hàng chậm luân chuyển có chủ đích:
--   mặt hàng có id chia hết cho 10: không có phiếu xuất nào trong 90 ngày cuối
--   mặt hàng có id chia hết cho 50: chưa từng được xuất
UPDATE issue_items ii SET product_id = ii.product_id + 1
FROM issue_orders io
WHERE io.id = ii.issue_order_id AND ii.product_id < 5000
  AND (ii.product_id % 50 = 0 OR (ii.product_id % 10 = 0 AND io.issue_date >= timestamptz '2026-08-27'));

-- 200 lần kiểm kê, 50 dòng / lần
INSERT INTO stock_takes (code, status, stock_take_date)
SELECT format('KK%s', lpad(g::text, 4, '0')), CASE WHEN g % 10 = 0 THEN 'PENDING' ELSE 'COMPLETED' END,
       timestamptz '2025-11-26' + random() * interval '365 days'
FROM generate_series(1, 200) g;

INSERT INTO stock_take_items (stock_take_id, product_id, location_id, system_qty, actual_qty)
SELECT s, floor(random() * 5000 + 1)::int + 0 * k, floor(random() * 200 + 1)::int, q, q + floor(random() * 5 - 2)::int
FROM generate_series(1, 200) s, generate_series(1, 50) k,
     LATERAL (SELECT floor(random() * 100 + 10)::int + 0 * k AS q) x;

-- Chỉ mục khóa ngoại và ngày chứng từ: để bộ tối ưu CÓ lựa chọn giữa các cách nối (STEP 4, 6).
-- (app hiện chưa có các chỉ mục này; đây là chỉ mục riêng của demo)
CREATE INDEX ON receipt_items (receipt_order_id);
CREATE INDEX ON issue_items (issue_order_id);
CREATE INDEX ON issue_items (product_id);
CREATE INDEX ON receipt_orders (receipt_date);
CREATE INDEX ON issue_orders (issue_date);

ANALYZE products, inventory, receipt_orders, receipt_items, issue_orders, issue_items, stock_takes, stock_take_items;

SELECT (SELECT count(*) FROM products)       AS products,
       (SELECT count(*) FROM inventory)      AS inventory,
       (SELECT count(*) FROM receipt_items)  AS receipt_items,
       (SELECT count(*) FROM issue_items)    AS issue_items,
       (SELECT count(*) FROM stock_take_items) AS stock_take_items;
