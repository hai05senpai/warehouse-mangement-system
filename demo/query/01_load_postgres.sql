--
-- Tạo schema riêng `qry_demo` (cùng cấu trúc bảng với app) với một năm chứng từ nhập / xuất / kiểm kê,
-- để chạy hai báo cáo của app: hàng chậm luân chuyển (UC-08) và nhập - xuất - tồn (UC-09).
-- Ngày "hôm nay" của demo cố định là 25/11/2026, để mỗi lần nạp cho cùng kết quả.
-- Chạy lại bất cứ lúc nào để đưa dữ liệu demo về trạng thái ban đầu.
-- Không đụng tới dữ liệu thật của app (schema public).
